// ---- generator library
{
  const ids = libraryEntries().map((e) => e.id);
  for (const id of ['web', 'desktop', 'rust-cli', 'python', 'nodejs', 'javascript', 'typescript', 'godot', 'vscode-extension', 'discord-bot', 'static-web', 'html-css', 'vite-web', 'sql', 'sqlite', 'data-pipeline', 'rest-api', 'node-server', 'os-bootloader']) assert.ok(ids.includes(id), id);
  for (const e of libraryEntries()) { const bad = validateGenerator(e.id).filter((c) => !c.ok); assert.deepEqual(bad, [], e.id + ' health'); }
  const all = exportAll();
  assert.ok(all['definitions/python.json'] && all['manifests/rust-cli.manifest.json'] && all['definitions/discord-bot.json']);
  assert.equal(exportGenerator('rust-cli').importable, false);
  // duplicate -> update -> downgrade protection -> builtin protection
  duplicateGenerator('python', 'python-mine', 'Python (mine)');
  assert.ok(libraryEntries().find((e) => e.id === 'python-mine').external);
  const def = toDefinition(PRESETS.python); def.generator = { ...def.generator, id: 'python-mine' };
  assert.equal(importIntoLibrary([JSON.stringify({ ...def, generator: { ...def.generator, version: '0.2.0' } })]).action, 'updated');
  assert.throws(() => importIntoLibrary([JSON.stringify({ ...def, generator: { ...def.generator, version: '0.1.0' } })]), /older/);
  assert.equal(importIntoLibrary([JSON.stringify({ ...def, generator: { ...def.generator, version: '0.1.0' } })], { allowDowngrade: true }).action, 'updated');
  assert.throws(() => importIntoLibrary([JSON.stringify(toDefinition(PRESETS.python))]), /built-in/);
  uninstallGenerator('python-mine');
  assert.throws(() => duplicateGenerator('rust-cli', 'x-copy'), /Definition-based/);
}

