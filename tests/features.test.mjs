// ---- process data: write, import, round trip
{
  const p = emptyProject('P'); const btn = createNode(p, 'button'); p.pages[0].root.children.push(btn);
  const data = { format: 'codiram-process', version: 1, variables: [{ name: 'count', type: 'Number', initial: '0' }, { name: 'msg' }],
    scripts: [{ name: 'Add', hat: { type: 'onClick', target: btn.name }, body: [
      { type: 'change_var', name: 'count', by: '1' },
      { type: 'if', cond: 'count > 3 and msg is empty', then: [{ type: 'set_var', name: 'msg', value: { $: 'text_join', a: '"n="', b: 'count' } }], else: [] },
      { type: 'repeat', times: '2', body: [{ type: 'alert', value: 'msg' }] }] }] };
  const r = readProcess(data, p);
  assert.deepEqual(r.errors, []);
  applyProcess(p, r.result);
  assert.deepEqual(lint(p), []);
  assert.equal(p.scripts[0].hat.args.target, btn.id, 'component name resolved to id');
  assert.deepEqual(p.scripts[0].body[1].args.cond.rows.map((x) => x.op), ['>', 'empty']);
  // export is readable and imports back to the same structure
  const out = exportProcess(p);
  assert.equal(out.scripts[0].hat.target, btn.name);
  const p2 = emptyProject('P2'); const b2 = createNode(p2, 'button'); b2.name = btn.name; p2.pages[0].root.children.push(b2);
  const r2 = readProcess(out, p2); assert.deepEqual(r2.errors, []); applyProcess(p2, r2.result);
  const shape = (list) => list.map((b) => [b.type, Object.keys(b.slots || {}).map((k) => shape(b.slots[k]))]);
  assert.deepEqual(shape(p2.scripts[0].body), shape(p.scripts[0].body));
  // errors are friendly
  const bad = readProcess({ scripts: [{ hat: { type: 'onClick', target: 'Nope' }, body: [{ type: 'change_var', name: 'zzz' }, { type: 'repeet' }] }] }, p2);
  assert.ok(bad.errors.some((e) => /Nope/.test(e)) && bad.errors.some((e) => /repeat/.test(e)) && bad.errors.some((e) => /zzz/.test(e)));
  assert.equal(bad.result, null);
  assert.deepEqual(parseCond('x contains "a" or y is empty').rows.length, 2);
}

// ---- snippets
{
  assert.ok(BUILTIN.length >= 8);
  const p = emptyProject('S'); const s = newScript(p, 'main', 'onLoad', {}); p.scripts.push(s);
  insertSnippet(p, BUILTIN.find((x) => x.id === 'sum-loop'), s.id);
  assert.ok(p.variables.some((v) => v.name === 'total') && s.body.length === 3);
  assert.deepEqual(lint(p).filter((x) => !/ページが未選択/.test(x.msg)), []);
  const before = s.body.length;
  insertSnippet(p, BUILTIN.find((x) => x.id === 'count-up'), s.id, s.body[0].id);
  assert.equal(s.body.length, before + 1); assert.equal(s.body[1].type, 'change_var', 'inserted after the chosen block');
  const mine = saveSnippet('My thing', s.body.slice(0, 2), p);
  assert.ok(mine.vars.some((v) => v.name === 'total'));
  assert.equal(userSnippets().length, 1);
  const json = exportSnippets(userSnippets());
  assert.equal(importSnippets(json), 1); assert.equal(allSnippets().length, BUILTIN.length + 2);
  assert.throws(() => importSnippets('{"format":"codiram-snippets","snippets":[{"blocks":[{"type":"nope"}]}]}'), /unknown block/);
  const q = emptyProject('Q'); insertSnippet(q, mine, null); // no script: blocks need one
  assert.equal(q.scripts.length, 0);
}

