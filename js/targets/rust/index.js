// Rust CLI generator: blocks -> IR -> a Cargo project (std only). Minimal on purpose: variables, conditions, loops,
// functions, console input/output and files.
import './blocks.js';
import { defineGenerator } from '../../sdk/index.js';
import '../../sdk/common-ir.js';
import { buildIR } from '../../ir.js';
import { J } from '../../i18n-helpers.js';
import { targetConfig } from '../../model.js';
import { generateRust } from './rust.js';

const CRATE = /^[a-z][a-z0-9_-]{0,63}$/;
const slug = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');

export const defaultRustConfig = (crateName = 'my_cli', name = 'My CLI') => ({
  type: 'rust-cli', crateName: CRATE.test(crateName) ? crateName : (slug(crateName) || 'my_cli'), version: '0.1.0', author: '', description: name,
});
export const validateRustConfig = (cfg) => {
  const out = [];
  if (!CRATE.test(cfg.crateName || '')) out.push('クレート名は 小文字英字で始まり、小文字・数字・_ - のみ で指定してください');
  if (!/^\d+\.\d+\.\d+/.test(cfg.version || '')) out.push('バージョンは 0.1.0 の形式で指定してください');
  return out;
};

const toml = (s) => JSON.stringify(String(s ?? ''));

export function rustProject(cfg, gen, project) {
  const files = {};
  files['Cargo.toml'] = `[package]
name = ${toml(cfg.crateName)}
version = ${toml(cfg.version)}
edition = "2021"
description = ${toml(cfg.description || project.name)}
${cfg.author ? `authors = [${toml(cfg.author)}]\n` : ''}
[dependencies]
`;
  files['src/main.rs'] = gen.main_rs;
  files['.gitignore'] = '/target\n';
  files['README.md'] = `# ${project.name}

A command-line program generated by [Codiram](https://github.com/Yumenyan/Codiram) (Rust CLI generator).
It is an ordinary Cargo project that depends on nothing but the Rust standard library — Codiram is not needed to build or edit it.

## Build and run

\`\`\`sh
cargo run
cargo build --release   # binary: target/release/${cfg.crateName}
\`\`\`

Requires Rust (https://rustup.rs).

## Files

| File | |
|---|---|
| \`src/main.rs\` | The program. Global variables live in the \`State\` struct; every handler / function receives \`&mut State\` |
| \`Cargo.toml\` | Package settings |
| \`codiram.project.json\` | The Codiram project — import it in Codiram to keep editing visually |
`;
  files['codiram.project.json'] = JSON.stringify(project, null, 2) + '\n';
  return files;
}

function generate(project, cfg) {
  cfg = cfg || targetConfig(project, 'rust-cli') || defaultRustConfig(slug(project.name), project.name);
  const ir = buildIR(project, 'rust-cli');
  const problems = [...ir.problems];
  validateRustConfig(cfg).forEach((msg) => problems.push({ msg, config: true }));
  const gen = generateRust(ir, cfg, project);
  problems.push(...gen.problems);
  if (project.models.length) problems.push({ msg: 'データモデルはまだ Rust CLI では使えません(変数のみ対応)', level: 'info' });
  return { files: rustProject(cfg, gen, project), problems, root: cfg.crateName, entry: 'src/main.rs' };
}

defineGenerator({
  id: 'rust-cli', order: 2, portable: true,
  name: J('Rust CLI', 'Rust CLI'),
  icon: '🦀',
  desc: J('Rust のコマンドラインアプリ(Cargo プロジェクト)を生成します', 'Generates a Rust command-line app (Cargo project)'),
  version: '0.1.0', language: ['rust'], platforms: ['windows', 'macos', 'linux'],
  supports: ['variables', 'conditions', 'loops', 'functions', 'filesystem', 'cli', 'io'],
  views: ['data', 'logic', 'output'],
  defaultConfig: defaultRustConfig,
  validateConfig: validateRustConfig,
  configFields: [
    { key: 'crateName', label: J('クレート名 (半角英小文字・数字・_ -)', 'Crate name (a-z, 0-9, _ -)'), ph: 'my_cli' },
    { key: 'version', label: J('バージョン', 'Version') },
    { key: 'author', label: J('作者', 'Author') },
    { key: 'description', label: J('説明', 'Description') },
  ],
  generate,
  lint: (project) => {
    const cfg = targetConfig(project, 'rust-cli');
    const out = buildIR(project, 'rust-cli').problems.filter((p) => !p.unsupported).map((p) => ({ script: p.script, block: p.block, msg: p.msg }));
    if (cfg) validateRustConfig(cfg).forEach((msg) => out.push({ script: null, block: null, msg }));
    return out;
  },
});
